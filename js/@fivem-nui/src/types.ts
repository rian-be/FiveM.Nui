/**
 * Represents an error in NUI communication.
 */
export interface NuiError {
  code: string;
  message: string;
}

/**
 * Window lifecycle envelope type sent by C# window management.
 */
export type NuiWindowAction = 'open' | 'close' | 'focus' | 'unfocus';

/**
 * Represents a message sent between C# and NUI.
 */
export interface NuiMessage {
  id?: string;
  type: 'request' | 'response' | 'event' | NuiWindowAction;
  /**
   * Absent on responses - the correlation `id` already identifies the call.
   */
  event?: string;
  payload?: unknown;
  success?: boolean;
  error?: NuiError;
}

/**
 * Result of an NUI operation.
 */
export interface NuiResult<T> {
  success: boolean;
  value?: T;
  error?: NuiError;
}

/**
 * Maps NUI event names to their request/response or payload shapes.
 *
 * Empty by default. A contracts module generated by `FiveM.Nui.Contracts`
 * augments this interface, so that {@link NuiClient} calls are checked against
 * the C# contract: a name that is not in the map fails to compile, and the
 * request and response types are inferred from the entry.
 *
 * @example
 * ```ts
 * declare module '@fivem-nui/core' {
 *   interface NuiEventMap {
 *     'inventory:use': { request: UseItemRequest; response: UseItemResponse };
 *     'player:healthChanged': { payload: HealthChanged };
 *   }
 * }
 * ```
 */
export interface NuiEventMap {}

/**
 * Event names accepted by {@link NuiClient}. Falls back to any string while
 * {@link NuiEventMap} is empty, so the client stays usable without generated
 * contracts and becomes strict as soon as the map is augmented.
 */
export type NuiEventKey = keyof NuiEventMap extends never ? string : keyof NuiEventMap;

/**
 * Request payload type for a mapped event, or `undefined` when the event takes
 * none. Resolves to `unknown` while {@link NuiEventMap} is empty.
 */
export type NuiEventRequest<E> = E extends keyof NuiEventMap
  ? NuiEventMap[E] extends { request: infer TRequest }
    ? TRequest
    : undefined
  : unknown;

/**
 * Response payload type for a mapped event. Resolves to `unknown` while
 * {@link NuiEventMap} is empty, preserving the untyped behaviour.
 */
export type NuiEventResponse<E> = E extends keyof NuiEventMap
  ? NuiEventMap[E] extends { response: infer TResponse }
    ? TResponse
    : unknown
  : unknown;

/**
 * Fire-and-forget payload type for a mapped event. Resolves to `unknown` while
 * {@link NuiEventMap} is empty.
 */
export type NuiEventPayload<E> = E extends keyof NuiEventMap
  ? NuiEventMap[E] extends { payload: infer TPayload }
    ? TPayload
    : unknown
  : unknown;
